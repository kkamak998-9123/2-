def 항목별_연도값(df: pd.DataFrame, 항목명: str) -> dict:
    """df에서 label 컬럼이 항목명과 일치하는 행을 찾아 {연도: 값} 딕셔너리로 반환.

    같은 연도에 연결/별도 재무제표가 동시에 존재하면 연결재무제표 값을 우선한다.
    """
    label_col = df.columns[0]
    matched = df[df[label_col] == 항목명]
    if matched.empty:
        return {}
    row = matched.iloc[0]

    후보: dict[str, tuple[float, bool]] = {}
    for col in df.columns[1:]:
        try:
            value = float(row[col])
        except (TypeError, ValueError):
            continue
        if pd.isna(value):
            continue
        연도 = 연도_라벨(col)
        연결 = 연결여부(col)
        if 연도 not in 후보 or (연결 and not 후보[연도][1]):
            후보[연도] = (value, 연결)
    return {연도: 값 for 연도, (값, _) in 후보.items()}


def 비율계산(분자값: dict, 분모값: dict, 단위: str) -> dict:
    """연도별 (분자/분모) 계산. 분모가 0/NaN이거나 값이 없는 연도는 제외."""
    결과 = {}
    for 연도 in sorted(set(분자값) & set(분모값)):
        num, den = 분자값[연도], 분모값[연도]
        if den == 0:
            continue
        비율값 = (num / den) * 100 if 단위 == "%" else num / den
        결과[연도] = 비율값
    return 결과
